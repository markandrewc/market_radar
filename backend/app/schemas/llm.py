"""LLM explanations (docs/LLM.md).

An `Explanation` is a short, plain-language reading generated by a model from a
server-built fact bundle. The model never supplies numbers or citations: every
sentence is validated against the facts, and the `SourceRef`s are resolved by
code before the answer leaves the server. Without a provider the deterministic
insight text is returned with `method = "fallback"`.
"""
from typing import Literal

from pydantic import BaseModel, Field

from .common import SourceRef

Language = Literal["en", "de"]
ExplainKind = Literal["insight", "policy", "item"]


class LlmStatus(BaseModel):
    """Whether explanations are available; never contains the key."""

    enabled: bool
    provider: str
    model: str
    language: str
    promptVersion: str
    dailyCap: int
    remainingTokens: int
    disclaimer: str


class ExplainRequest(BaseModel):
    kind: ExplainKind = "insight"
    insightId: str | None = None  # e.g. "policy:rss_policy:p1" or "demand:it-support"
    itemId: str | None = None  # market_items.id of a policy or context record
    roleId: str | None = None
    language: Language | None = None  # None -> config.LLM_LANGUAGE


class ExplainTarget(BaseModel):
    kind: str
    id: str
    label: str


class CitedSentence(BaseModel):
    text: str
    sources: list[SourceRef] = Field(default_factory=list)


class Explanation(BaseModel):
    target: ExplainTarget
    language: str
    text: str  # sentences joined, citations already included
    sentences: list[CitedSentence] = Field(default_factory=list)
    method: Literal["model", "fallback"]
    model: str | None = None
    cached: bool = False
    generatedAt: str
    disclaimer: str
    usedSources: list[SourceRef] = Field(default_factory=list)


class AskRequest(BaseModel):
    question: str = Field(min_length=3, max_length=300)
    roleId: str | None = None
    language: Language | None = None  # None -> config.LLM_LANGUAGE


class AskAnswer(BaseModel):
    question: str
    text: str
    sentences: list[CitedSentence] = Field(default_factory=list)
    method: Literal["model", "fallback", "no_data"]
    usedSources: list[SourceRef] = Field(default_factory=list)
    followUps: list[str] = Field(default_factory=list)
    cached: bool = False
    model: str | None = None
    generatedAt: str
    disclaimer: str
